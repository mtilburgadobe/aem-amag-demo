/**
 * Parser: image-text-card (block table "image-text-card").
 * Source: https://www.amag.ch/de/service.html —
 * `.amag-content > section.section:has(.amag-maxiTeaserBild)` (DOM section 2: three image
 * teasers "Top Services" / "Reifen und Räder" / "Hilfe im Schadenfall").
 *
 * Authoring rows (blocks/image-text-card/image-text-card.js, cells read by role) — as on
 * /en/services: ONE ROW PER CARD, three cells:
 *   <img card image> | [<p>eyebrow</p>]<h3>title</h3><p>text</p> | <p><strong><a href>button label</a></strong></p>
 * Iteration: `.amag-maxiTeaserBild` (document order). The source title is
 * `p.amag-maxiTeaserBild__headline` (authored as <h3>); an empty topline is skipped.
 * Dropped: the button's arrow <svg> (generated by the block, aria-hidden).
 * Anything else with text in the instance section (none on /de/service) is kept in front of the
 * block so no content is lost.
 */
const ORIGIN = 'https://www.amag.ch';
const txt = (n) => (n ? n.textContent.replace(/\s+/g, ' ').trim() : '');
const abs = (u) => {
  if (!u) return '';
  const s = u.trim();
  if (/^(data:|https?:)/i.test(s)) return s;
  if (s.startsWith('//')) return `https:${s}`;
  try { return new URL(s, `${ORIGIN}/`).href; } catch (e) { return s; }
};
function toImg(img, document) {
  if (!img) return null;
  const src = abs(img.getAttribute('src') || img.getAttribute('data-src'));
  if (!src || src.startsWith('data:')) return null;
  const out = document.createElement('img');
  out.setAttribute('src', src);
  out.setAttribute('alt', (img.getAttribute('alt') || '').trim());
  return out;
}
const mk = (document, tag, ...kids) => {
  const e = document.createElement(tag);
  kids.flat().forEach((k) => { if (k != null && k !== '') e.append(k); });
  return e;
};

export default function parse(element, { document }) {
  const cards = element.matches('.amag-maxiTeaserBild')
    ? [element]
    : [...element.querySelectorAll('.amag-maxiTeaserBild')].filter((c) => !c.parentElement.closest('.amag-maxiTeaserBild'));

  const cells = [];
  cards.forEach((card) => {
    const image = toImg(card.querySelector('img.amag-maxiTeaserBild__img') || card.querySelector('picture img, img'), document);
    const topline = txt(card.querySelector('.amag-maxiTeaserBild__topline'));
    const title = txt(card.querySelector('.amag-maxiTeaserBild__headline, h2, h3'));
    const copy = [...card.querySelectorAll('.amag-maxiTeaserBild__text')].map(txt).filter(Boolean);
    const btn = card.querySelector('a.amag-maxiTeaserBild__btn[href]') || card.querySelector('a[href]');
    const label = btn ? txt(btn.querySelector('.btn__text') || btn) : '';
    if (!title && !image) return;

    const text = [];
    if (topline) text.push(mk(document, 'p', topline));
    if (title) text.push(mk(document, 'h3', title));
    copy.forEach((c) => text.push(mk(document, 'p', c)));

    let cta = '';
    if (btn && label) {
      const a = mk(document, 'a', label);
      a.setAttribute('href', btn.getAttribute('href'));
      cta = mk(document, 'p', mk(document, 'strong', a));
    }
    cells.push([image || '', text, cta]);
  });

  if (!cells.length) {
    element.replaceWith(...element.childNodes);
    return;
  }

  const block = WebImporter.Blocks.createBlock(document, { name: 'image-text-card', cells });
  if (!element.matches('.amag-maxiTeaserBild')) {
    // keep any other authored text of the instance section (outside the cards) before the block
    cards.forEach((c) => c.remove());
    const rest = [...element.querySelectorAll('h1, h2, h3, h4, h5, h6, p, ul, ol')]
      .filter((n) => txt(n) && !n.parentElement.closest('h1, h2, h3, h4, h5, h6, p, ul, ol'));
    rest.forEach((n) => element.before(n));
  }
  element.replaceWith(block);
}
