/**
 * Parser: direct-entry (block table "Direct Entry").
 * Source: https://www.amag.ch/de/garagenuebersicht/garage-buelach.html — `.amag-direct-entry`
 * (section 21, fixed "Services" pill + "Direkt zu" pop-up).
 *
 * Authoring rows (blocks/direct-entry/direct-entry.js, read by role — same order as the
 * existing /en/services content):
 *   1. closed face:  <p><img icon></p> | <p>Services</p>      (img + plain <p>, no link)
 *   2. open face:    <p><img close></p> | <p>Schliessen</p>
 *   3. topline:      <p>Direkt zu</p>
 *   4. entries:      <p><img icon></p> | <p><a href>Probefahrt</a></p>   (one row per entry)
 * Dropped: each entry's chevron <svg> (generated by the block, aria-hidden) and the backdrop.
 */
const ORIGIN = 'https://www.amag.ch';
const txt = (n) => (n ? n.textContent.replace(/\s+/g, ' ').trim() : '');
const abs = (u) => {
  if (!u) return '';
  const s = u.trim();
  if (/^(data:|https?:)/i.test(s)) return s;
  if (s.startsWith('//')) return `https:${s}`;
  try { return new URL(s, `${ORIGIN}/`).href; } catch (e) { return s; }
};
function toImg(img, document) {
  if (!img) return null;
  const src = abs(img.getAttribute('src') || img.getAttribute('data-src'));
  if (!src) return null;
  const out = document.createElement('img');
  out.setAttribute('src', src);
  out.setAttribute('alt', (img.getAttribute('alt') || '').trim());
  return out;
}
const mk = (document, tag, ...kids) => {
  const e = document.createElement(tag);
  kids.flat().forEach((k) => { if (k != null && k !== '') e.append(k); });
  return e;
};

export default function parse(element, { document }) {
  const cells = [];

  // Pill faces: closed (open-button = "Services") first, then the close face.
  ['.amag-direct-entry__button--open', '.amag-direct-entry__button--close'].forEach((sel) => {
    const face = element.querySelector(sel);
    if (!face) return;
    const icon = toImg(face.querySelector('img'), document);
    const label = txt(face.querySelector('.amag-direct-entry__label') || face);
    if (!label) return;
    cells.push([icon ? mk(document, 'p', icon) : '', mk(document, 'p', label)]);
  });

  // Pop-up topline.
  const topline = txt(element.querySelector('.amag-direct-entry__pop-up-topline'));
  if (topline) cells.push([mk(document, 'p', topline)]);

  // Pop-up entries.
  let entries = [...element.querySelectorAll('a.amag-direct-entry__pop-up-element[href]')];
  if (!entries.length) entries = [...element.querySelectorAll('.amag-direct-entry__pop-up a[href]')];
  entries.forEach((entry) => {
    const label = txt(entry.querySelector('.amag-direct-entry__link') || entry);
    if (!label) return;
    const icon = toImg(entry.querySelector('img'), document);
    const a = mk(document, 'a', label);
    a.setAttribute('href', entry.getAttribute('href'));
    cells.push([icon ? mk(document, 'p', icon) : '', mk(document, 'p', a)]);
  });

  if (!entries.length) {
    element.replaceWith(...element.childNodes);
    return;
  }

  const block = WebImporter.Blocks.createBlock(document, { name: 'Direct Entry', cells });
  element.replaceWith(block);
}
