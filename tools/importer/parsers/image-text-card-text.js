/**
 * Parser: image-text-card-text (block table "Image Text Card Text").
 * Source: https://www.amag.ch/de/garagenuebersicht/garage-buelach.html — `.amag-maxiTeaser`
 * (section 11 "AMAG Fleet & Services", section 18 "JOBS BEI AMAG").
 *
 * Authoring row (blocks/image-text-card-text/image-text-card-text.js, ONE row, read by role):
 *   <p>AMAG Fleet &amp; Services</p>                 (eyebrow: short <p> BEFORE the heading)
 *   <h2>Individuelle Lösungen für Flottenkunden</h2>  (source: div.__headline -> <h2>)
 *   <p>text</p>
 *   <p><strong><a href>Flotten-Team kontaktieren</a></strong></p>  (gozilla button)
 * The button's arrow glyph is GENERATED by the block (aria-hidden), so the source's inline
 * arrow <svg> is not authored (the block reads only the link text).
 */
const txt = (n) => (n ? n.textContent.replace(/\s+/g, ' ').trim() : '');
const mk = (document, tag, ...kids) => {
  const e = document.createElement(tag);
  kids.flat().forEach((k) => { if (k != null && k !== '') e.append(k); });
  return e;
};

export default function parse(element, { document }) {
  const eyebrow = txt(element.querySelector('.amag-maxiTeaser__description__theme'));
  const headline = txt(element.querySelector('.amag-maxiTeaser__description__headline, h2, h3'));
  const textBox = element.querySelector('.amag-maxiTeaser__description__text');
  let paras = textBox ? [...textBox.querySelectorAll('p')].map(txt).filter(Boolean) : [];
  if (!paras.length && txt(textBox)) paras = [txt(textBox)];

  const btn = element.querySelector('a.amag-maxiTeaser__btn[href]')
    || [...element.querySelectorAll('a[href]')].find((a) => txt(a));
  const label = btn ? txt(btn.querySelector('.btn__text') || btn) : '';

  const cell = [];
  if (eyebrow) cell.push(mk(document, 'p', eyebrow));
  if (headline) cell.push(mk(document, 'h2', headline));
  paras.forEach((p) => cell.push(mk(document, 'p', p)));
  if (btn && label) {
    const a = mk(document, 'a', label);
    a.setAttribute('href', btn.getAttribute('href'));
    cell.push(mk(document, 'p', mk(document, 'strong', a)));
  }

  if (!headline && !paras.length) {
    element.replaceWith(...element.childNodes);
    return;
  }

  const cells = [[cell]];
  const block = WebImporter.Blocks.createBlock(document, { name: 'Image Text Card Text', cells });
  element.replaceWith(block);
}
