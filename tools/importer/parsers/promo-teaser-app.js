/**
 * Parser: promo-teaser-app (block table "Promo Teaser App").
 * Source: https://www.amag.ch/de/garagenuebersicht/garage-buelach.html — `.amag-app-download`
 * (section 10 "AMAG App").
 *
 * Authoring row (blocks/promo-teaser-app/promo-teaser-app.js, ONE row, read by role):
 *   <p><img teaser image></p> |
 *   <h2>AMAG App: Ihre Garage in einer App</h2><p>copy</p>
 *   <p><a href=apple><img App Store></a> <a href=google><img Google Play></a></p>  (badges)
 *   <p><em><a href=/de/service/top-services/app.html>Zur AMAG App</a></em></p>     (violet CTA)
 * The CTA is one text link; its check-circle glyph is GENERATED by the block (aria-hidden), so
 * the source's inline w_check-circle icon is not authored (the block would discard it).
 * Badge images carry no alt on the source; the block labels each badge link by its image alt,
 * so the alt is derived from the badge link class (--IOS -> "App Store", --Android -> "Google Play").
 */
const ORIGIN = 'https://www.amag.ch';
const txt = (n) => (n ? n.textContent.replace(/\s+/g, ' ').trim() : '');
const abs = (u) => {
  if (!u) return '';
  const s = u.trim();
  if (/^(data:|https?:)/i.test(s)) return s;
  if (s.startsWith('//')) return `https:${s}`;
  try { return new URL(s, `${ORIGIN}/`).href; } catch (e) { return s; }
};
function toImg(img, document, alt) {
  if (!img) return null;
  const src = abs(img.getAttribute('src') || img.getAttribute('data-src'));
  if (!src) return null;
  const out = document.createElement('img');
  out.setAttribute('src', src);
  out.setAttribute('alt', (alt != null ? alt : (img.getAttribute('alt') || '')).trim());
  return out;
}
const mk = (document, tag, ...kids) => {
  const e = document.createElement(tag);
  kids.flat().forEach((k) => { if (k != null && k !== '') e.append(k); });
  return e;
};

export default function parse(element, { document }) {
  const image = toImg(element.querySelector('.amag-app-download__image img, picture img'), document);
  const heading = element.querySelector('.amag-app-download__text-headline, h2, h3');
  const copy = [...element.querySelectorAll('.amag-app-download__text-copy')].map(txt).filter(Boolean);

  const content = [];
  if (heading && txt(heading)) content.push(mk(document, 'h2', txt(heading)));
  copy.forEach((c) => content.push(mk(document, 'p', c)));

  const badges = [...element.querySelectorAll('.amag-app-download__link-badges a[href]')].map((a) => {
    const cls = a.className || '';
    const fallbackAlt = /ios/i.test(cls) ? 'App Store' : (/android/i.test(cls) ? 'Google Play' : '');
    const srcImg = a.querySelector('img');
    const alt = (srcImg && srcImg.getAttribute('alt')) || fallbackAlt;
    const img = toImg(srcImg, document, alt);
    if (!img) return null;
    const link = mk(document, 'a', img);
    link.setAttribute('href', a.getAttribute('href'));
    return link;
  }).filter(Boolean);
  if (badges.length) {
    const p = document.createElement('p');
    badges.forEach((b, i) => { if (i) p.append(' '); p.append(b); });
    content.push(p);
  }

  const ctaSrc = element.querySelector('a.amag-app-download__link-cta[href]')
    || [...element.querySelectorAll('.amag-app-download__link > a[href]')].find((a) => txt(a));
  if (ctaSrc && txt(ctaSrc)) {
    const a = mk(document, 'a', txt(ctaSrc));
    a.setAttribute('href', ctaSrc.getAttribute('href'));
    content.push(mk(document, 'p', mk(document, 'em', a)));
  }

  if (!content.length && !image) {
    element.replaceWith(...element.childNodes);
    return;
  }

  const cells = [[image ? mk(document, 'p', image) : '', content]];
  const block = WebImporter.Blocks.createBlock(document, { name: 'Promo Teaser App', cells });
  element.replaceWith(block);
}
